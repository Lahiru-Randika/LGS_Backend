========================================================= */

-- Compatibility function: UTC_TIMESTAMP()
CREATE OR REPLACE FUNCTION UTC_TIMESTAMP()
RETURNS TIMESTAMPTZ AS $$
  SELECT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC');
$$ LANGUAGE sql STABLE;

-- Compatibility function: UTC_DATE()
CREATE OR REPLACE FUNCTION UTC_DATE()
RETURNS DATE AS $$
  SELECT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::date;
$$ LANGUAGE sql STABLE;

-- Compatibility function: auto-update updated_at columns
CREATE OR REPLACE FUNCTION trigger_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Compatibility operators for boolean = integer and integer = boolean
CREATE OR REPLACE FUNCTION bool_eq_int(b boolean, i integer)
RETURNS boolean AS $$
  SELECT b = (i <> 0);
$$ LANGUAGE sql IMMUTABLE;

CREATE OR REPLACE FUNCTION int_eq_bool(i integer, b boolean)
RETURNS boolean AS $$
  SELECT (i <> 0) = b;
$$ LANGUAGE sql IMMUTABLE;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_operator o
    JOIN pg_type l ON l.oid = o.oprleft
    JOIN pg_type r ON r.oid = o.oprright
    WHERE o.oprname = '=' AND l.typname = 'bool' AND r.typname = 'int4'
  ) THEN
    CREATE OPERATOR = (
      LEFTARG = boolean,
      RIGHTARG = integer,
      FUNCTION = bool_eq_int,
      COMMUTATOR = =
    );
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_operator o
    JOIN pg_type l ON l.oid = o.oprleft
    JOIN pg_type r ON r.oid = o.oprright
    WHERE o.oprname = '=' AND l.typname = 'int4' AND r.typname = 'bool'
  ) THEN
    CREATE OPERATOR = (
      LEFTARG = integer,
      RIGHTARG = boolean,
      FUNCTION = int_eq_bool,
      COMMUTATOR = =
    );
  END IF;
END $$;

