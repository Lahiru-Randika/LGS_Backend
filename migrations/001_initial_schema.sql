DECLARE
  t text;
BEGIN
  FOR t IN SELECT unnest(ARRAY[
    'departments', 'wards', 'users', 'map_sources', 'buildings',
    'geocode_cache', 'service_requests', 'booking_details',
    'public_facility_profiles', 'inspections', 'approval_requests',
    'notification_preferences', 'properties', 'tax_accounts',
    'news_posts', 'contact_messages'
  ])
  LOOP
    EXECUTE format('
      DROP TRIGGER IF EXISTS trg_set_updated_at_%1$I ON %1$I;
      CREATE TRIGGER trg_set_updated_at_%1$I
      BEFORE UPDATE ON %1$I
      FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();
    ', t);
  END LOOP;
END $$;
